"""Round 4, part A3: is the model as reliable early in the season? Accuracy by week bucket (1-4, 5-8, 9+), and fixes.

Fix keep rule: lower RMSE in Weeks 1-4 on BOTH development (2012-19) and holdout (2020-25), and no worse RMSE over the whole
season on either. Writes results/round4_early.md and .csv.
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import warnings; warnings.filterwarnings('ignore')
import numpy as np, pandas as pd
from scipy.stats import norm
from nflmodel.common import RESULTS, CACHE, config
from nflmodel.features import load_all, build_features
from nflmodel.extra import build_extra
from nflmodel.metrics import evaluate, line_as_model
from nflmodel.teamtable import build_team_table
from factors_round2 import load, wf, X_of, DEV, HOLD
import baseline, round3_rankings as r3

CFG = config(); A, B = CFG['features'], CFG['line_adjust']
BUCKETS = (('Weeks 1-4', range(1, 5)), ('Weeks 5-8', range(5, 9)), ('Weeks 9-18', range(9, 19)))
PERIODS = (('Development 2012-19', DEV), ('Holdout 2020-25', HOLD), ('2026', [2026]))


def early_only(f, feats, seasons):
    """Separate weights for Weeks 1-4, fitted only on Weeks 1-4 of earlier seasons; normal weights otherwise."""
    full = wf(f, feats, seasons); out = []
    for S in seasons:
        tr = f[(f.season >= 2009) & (f.season < S) & f.result.notna() & (f.game_type == 'REG') & (f.week <= 4)]
        te = full[(full.season == S) & (full.week <= 4)].copy()
        if te.empty: continue
        X = X_of(tr, feats); b = np.linalg.lstsq(X, tr.result.values, rcond=None)[0]; sig = np.sqrt(np.mean((tr.result.values - X @ b) ** 2))
        te['pred'] = X_of(te, feats) @ b; te['prob'] = norm.cdf(te.pred / sig); out.append(te)
    e = pd.concat(out); return pd.concat([full[~full.game_id.isin(e.game_id)], e])


def main():
    f = load()
    M = {'Original workbook model': baseline.predict(range(2012, 2027)), 'Model only': wf(f, A, range(2012, 2027)),
         'TIP (adjusted line)': wf(f, B, range(2012, 2027), track='B')}
    M['Vegas closing line'] = line_as_model(M['Model only'])
    L = ['# Round 4: accuracy by part of the season (generated by research/round4_early.py)\n', '## Tips right and error by week bucket\n',
         '| Period | Weeks | Original | Model only | TIP | Line | Model RMSE | Line RMSE |', '|---|---|---|---|---|---|---|---|']
    rows = []
    for pl, S in PERIODS:
        for bl, W in BUCKETS:
            e = {k: evaluate(v[v.season.isin(S) & v.week.isin(W)]) for k, v in M.items()}
            if e['Model only']['games'] == 0: continue
            L.append(f"| {pl} | {bl} ({e['Model only']['games']} games) | " + ' | '.join(f"{e[k]['SU_acc']*100:.1f}%" for k in M) +
                     f" | {e['Model only']['RMSE']:.2f} | {e['Vegas closing line']['RMSE']:.2f} |")
            rows += [dict(period=pl, weeks=bl, model=k, **{x: e[k][x] for x in ('games', 'SU_acc', 'RMSE', 'LogLoss')}) for k in M]
    # rankings by bucket
    data = load_all(); g, tg = data[0], data[1]
    T = pd.read_pickle(os.path.join(CACHE, 'features', 'team_table.pkl'))
    X, C, tr = r3.methods(T, g, tg, data, f)
    names = ['Model power (current, incl. QB)', 'nfelo QB-adjusted Elo', 'Original workbook PR score', 'Win % (record), point diff breaks ties']
    L += ['\n## Power-ranking accuracy by week the ranking was published (share of remaining games won by the higher-ranked team)\n',
          '| Period | Published before | ' + ' | '.join(names) + ' |', '|---|---|' + '---|' * len(names)]
    for pl, S in PERIODS[:2]:
        for bl, W in (('Weeks 2-4', range(2, 5)), ('Weeks 5-8', range(5, 9)), ('Weeks 9-17', range(9, 18))):
            s = r3.score_methods(X, tr, names, S, W)
            L.append(f'| {pl} | {bl} | ' + ' | '.join(f"{s.loc[n].ros_acc*100:.1f}%" for n in names) + ' |')
    # fixes for the early weeks
    L += ['\n## Fixes tested for Weeks 1-4\n', 'Keep rule: lower Weeks 1-4 RMSE on both periods, whole-season RMSE not worse on either.\n',
          '| Fix | Wk 1-4 Δ RMSE dev | Wk 1-4 Δ RMSE holdout | Season Δ RMSE dev | Season Δ RMSE holdout | Wk 1-4 Δ tips dev | Wk 1-4 Δ tips holdout | Result |', '|---|---|---|---|---|---|---|---|']
    base = {p: wf(f, A, S) for p, S in (('dev', DEV), ('hold', HOLD))}
    def ev(d, early): x = d[d.week <= 4] if early else d; return evaluate(x)
    fixes = [('nfelo weighted differently early', lambda S: wf(f, A + ['nfelo_pts*early'], S)),
             ('QB value weighted differently early', lambda S: wf(f, A + ['qb_d*early'], S)),
             ('Results rating weighted differently early', lambda S: wf(f, A + ['res_d*early'], S)),
             ('Market + nfelo weighted differently early', lambda S: wf(f, A + ['mkt_d*early', 'nfelo_pts*early'], S)),
             ('Separate weights fitted on Weeks 1-4 only', lambda S: early_only(f, A, S))]
    # longer carry-over of last season's market rating (rebuild features with more off-season memory)
    for off in (4.0, 10.0):
        p2 = dict(CFG['ratings'], m_off=off)
        f2 = build_extra(build_features(p2, data=data), g, tg).merge(f[['game_id', 'model_pred', 'gametime', 'weekday']], on='game_id', how='left')
        fixes.append((f'Market rating keeps less of last season (off-season = {off:.0f} extra weeks)', lambda S, f2=f2: wf(f2, A, S)))
    log = []
    for name, fn in fixes:
        r = {p: fn(S) for p, S in (('dev', DEV), ('hold', HOLD))}
        d = {p: (ev(r[p], True)['RMSE'] - ev(base[p], True)['RMSE'], ev(r[p], False)['RMSE'] - ev(base[p], False)['RMSE'],
                 (ev(r[p], True)['SU_acc'] - ev(base[p], True)['SU_acc']) * 100) for p in r}
        kept = d['dev'][0] < 0 and d['hold'][0] < 0 and d['dev'][1] <= 0.001 and d['hold'][1] <= 0.001
        L.append(f"| {name} | {d['dev'][0]:+.3f} | {d['hold'][0]:+.3f} | {d['dev'][1]:+.3f} | {d['hold'][1]:+.3f} | {d['dev'][2]:+.1f} | {d['hold'][2]:+.1f} | {'**helped (kept)**' if kept else 'not kept'} |")
        log.append(dict(fix=name, early_dev=d['dev'][0], early_hold=d['hold'][0], season_dev=d['dev'][1], season_hold=d['hold'][1], kept=kept)); print(name, kept, flush=True)
    pd.DataFrame(rows).to_csv(os.path.join(RESULTS, 'round4_early.csv'), index=False)
    pd.DataFrame(log).to_csv(os.path.join(RESULTS, 'round4_early_fixes.csv'), index=False)
    open(os.path.join(RESULTS, 'round4_early.md'), 'w').write('\n'.join(L) + '\n'); print('\n'.join(L))


if __name__ == '__main__':
    main()
