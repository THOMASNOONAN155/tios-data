"""Round 5: better offence and defence rankings (Tom, Nov 2026: 'Tampa Bay has the best defence?').

Question: which offence / defence rating, published before week w, best predicts each team's points scored / allowed
over the REST of that season? Same walk-forward design as round 3 (results/round3_rankings.md, 'Offence and defence
rankings'): weeks 4-14, Spearman rank correlation per (season, week), averaged.

Candidates (all opponent-adjusted with the same ridge, half-life and window as the model's EPA rating, config.json):
  E      EPA per play                         (current rank)
  E_to   EPA with turnovers at half weight    (interceptions and lost fumbles are partly luck)
  E_nt   EPA with turnover plays removed
  P      points per game
  S      success rate
and z-score blends of them. Keep rule (project rules): a candidate replaces the current rank only if it is better on
BOTH development (2012-19) and holdout (2020-25), for offence and defence separately.
Writes results/round5_offdef.md and .csv.
"""
import os, sys, itertools
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import warnings; warnings.filterwarnings('ignore')
import numpy as np, pandas as pd
from scipy.stats import spearmanr
from nflmodel.common import RESULTS, CACHE, TEAMS, config
from nflmodel.features import load_all
from nflmodel.ratings import epa_ratings

DEV, HOLD = range(2012, 2020), range(2020, 2026)


def team_table(g, tg):
    x = pd.read_csv(os.path.join(CACHE, 'team_games_x.csv'))[['game_id', 'team', 'epa_to50', 'epa_noto']]
    x['team'] = x.team.replace({'LAR': 'LA', 'JAC': 'JAX', 'WSH': 'WAS'})
    t = tg.merge(x, on=['game_id', 'team'], how='left')
    sc = g[['game_id', 'home_team', 'home_score', 'away_score']]
    t = t.merge(sc, on='game_id', how='left', suffixes=('', '_g'))
    t['pf'] = np.where(t.team == t.home_team_g if 'home_team_g' in t else t.team == t.home_team, t.home_score, t.away_score)
    t['pts'] = t.pf * t.plays          # epa_ratings divides by plays -> y = points per game
    t['epa_to50'] = t.epa_to50.fillna(t.epa); t['epa_noto'] = t.epa_noto.fillna(t.epa)
    return t


def ratings(t, g, p):
    R = {}
    for k, m in (('E', 'epa'), ('E_to', 'epa_to50'), ('E_nt', 'epa_noto'), ('P', 'pts'), ('S', 'succ')):
        R[k] = epa_ratings(t, 2010, p['e_hl'], p['e_off'], p['e_lam'], gt=False, metric=m, schedule=g)
        print('rated', k, flush=True)
    return R


def z(v):
    s = np.std(v); return (v - np.mean(v)) / s if s > 0 else v * 0


def candidates():
    base = ['E', 'E_to', 'E_nt', 'P', 'S']
    out = [(b,) for b in base]
    for e in ('E', 'E_to', 'E_nt'):
        out += [(e, 'P'), (e, 'S'), (e, 'P', 'S')]
    out += [('P', 'S')]
    return out


def main():
    p = config()['ratings']; data = load_all(); g, tg = data[0], data[1]
    t = team_table(g, tg); R = ratings(t, g, p)
    gg = g[(g.game_type == 'REG') & g.result.notna()]
    h = gg[['season', 'week', 'home_team', 'home_score', 'away_score']].set_axis(['season', 'week', 'team', 'pf', 'pa'], axis=1)
    a = gg[['season', 'week', 'away_team', 'away_score', 'home_score']].set_axis(['season', 'week', 'team', 'pf', 'pa'], axis=1)
    tr = pd.concat([h, a])
    cands = candidates(); rows = []
    for side in ('off', 'def'):
        for c in cands:
            acc = {'dev': [], 'hold': []}
            for s in list(DEV) + list(HOLD):
                lab = 'dev' if s in DEV else 'hold'; ts = tr[tr.season == s]
                for w in range(4, 15):
                    if (s, w) not in R['E']: continue
                    r = ts[ts.week >= w]
                    if r.empty: continue
                    tgt = r.groupby('team').pf.mean() if side == 'off' else r.groupby('team').pa.mean()
                    j = 1 if side == 'off' else 2
                    sc = sum(z(R[k][(s, w)][j]) for k in c) / len(c)
                    sc = pd.Series(sc, index=TEAMS).reindex(tgt.index)
                    acc[lab].append(spearmanr(sc, tgt).correlation)
            rows.append(dict(side=side, rating=' + '.join(c), dev=np.nanmean(acc['dev']), hold=np.nanmean(acc['hold'])))
            print(rows[-1], flush=True)
    D = pd.DataFrame(rows)
    D.to_csv(os.path.join(RESULTS, 'round5_offdef.csv'), index=False)
    L = ['# Round 5: offence and defence rankings (generated by research/round5_offdef.py)\n',
         'Rank correlation between a rating published before week w (weeks 4-14) and the team\'s remaining-season points scored '
         '(offence) or allowed (defence). Higher = better. Every rating is opponent-adjusted the same way as the model\'s EPA rating. '
         'E = EPA/play, E_to = EPA with turnovers at half weight, E_nt = EPA without turnover plays, P = points, S = success rate; '
         '"+" = equal-weight blend of z-scores. Keep rule: better than the current rating (E) on both development (2012-19) and holdout (2020-25).\n']
    for side, nm in (('off', 'Offence (predicts points scored)'), ('def', 'Defence (predicts points allowed)')):
        d = D[D.side == side].copy(); b = d[d.rating == 'E'].iloc[0]
        d['verdict'] = np.where((d.dev > b.dev) & (d.hold > b.hold), 'better on both', np.where(d.rating == 'E', 'current', 'not better on both'))
        L += [f'\n## {nm}\n', '| Rating | Corr dev | Corr holdout | Verdict |', '|---|---|---|---|']
        for x in d.sort_values('hold', ascending=False).itertuples():
            L.append(f'| {x.rating} | {x.dev:.3f} | {x.hold:.3f} | {x.verdict} |')
    open(os.path.join(RESULTS, 'round5_offdef.md'), 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
