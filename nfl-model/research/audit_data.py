"""Round 4, part A1: spot-check the data against independent sources. Writes results/audit_data.md.

Sources compared (all real downloads):
  scores ........ nflverse games.csv  vs  nfelo (separately maintained)  vs  final score in nflverse play-by-play
                  vs  your workbook (2026)
  lines ......... games.csv closing spread/total  vs  your workbook's 5-source consensus close (2026)
  starting QB ... games.csv  vs  nfelo's starter  vs  the QB with most dropbacks in play-by-play
  team stats .... our play-by-play aggregates  vs  nflverse official team stats (stats_team_week) 2018, 2025, 2026
  player stats .. our targets / QB dropbacks  vs  nflverse official player stats (stats_player_week) 2012, 2018, 2024, 2026
  QB EPA 2026 ... ours  vs  the QB table in your original workbook (qbdata.py, through Week 8)
"""
import os, sys, re, unicodedata
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import warnings; warnings.filterwarnings('ignore')
import numpy as np, pandas as pd
from nflmodel.common import RESULTS, CACHE, RAW, INPUTS, load_games, FRANCHISE

AUD = os.path.join(RAW, 'audit'); FIX = {'OAK': 'LV', 'SD': 'LAC', 'STL': 'LA', 'LAR': 'LA', 'WSH': 'WAS', 'JAC': 'JAX'}
canon = lambda gid: '_'.join(p if i < 2 else FIX.get(p, p) for i, p in enumerate(str(gid).split('_')))


def norm_name(n):
    n = unicodedata.normalize('NFKD', str(n)).encode('ascii', 'ignore').decode().lower()
    n = re.sub(r'\b(jr|sr|ii|iii|iv|v)\b\.?', '', n); n = re.sub(r'[^a-z ]', '', n).split()
    return (n[0][0] + ' ' + n[-1]) if len(n) >= 2 else ' '.join(n)


def main():
    g = load_games(); g['key'] = g.game_id.map(canon)
    L = ['# Data audit (generated by research/audit_data.py)\n']
    played = g[g.result.notna()]
    # ---------- scores vs nfelo
    ne = pd.read_csv(os.path.join(RAW, 'nfelo_qb_elos.csv'), low_memory=False); ne = ne[ne.season >= 2006].copy(); ne['key'] = ne.game_id.map(canon)
    m = played.merge(ne, on='key', how='inner')
    m['t1'] = m.team1.replace(FIX)
    hs = np.where(m.t1 == m.home_team, m.score1, m.score2); as_ = np.where(m.t1 == m.home_team, m.score2, m.score1)
    bad = m[(hs != m.home_score) | (as_ != m.away_score)]
    L += ['## Scores', '', f'- **nflverse vs nfelo:** {len(m):,} games matched (2006–2026); score mismatches: **{len(bad)}**.']
    if len(bad): L.append('  ' + ', '.join(bad.game_id_x.head(10)))
    # ---------- scores vs play-by-play final score (sample seasons)
    rows = []
    for s in (2008, 2014, 2020, 2025, 2026):
        p = pd.read_parquet(os.path.join(RAW, f'pbp_{s}.parquet'), columns=['game_id', 'total_home_score', 'total_away_score'])
        fin = p.groupby('game_id')[['total_home_score', 'total_away_score']].max()
        x = played[played.season == s].set_index('game_id').join(fin, how='inner')
        rows.append((s, len(x), int(((x.home_score != x.total_home_score) | (x.away_score != x.total_away_score)).sum())))
    L.append('- **games.csv vs final score in play-by-play:** ' + '; '.join(f'{s}: {n} games, {b} mismatches' for s, n, b in rows) + '.')
    # ---------- 2026 workbook (scores + lines)
    wbp = os.path.join(INPUTS, 'original_workbook_2026_games.csv')
    if os.path.exists(wbp):
        w = pd.read_csv(wbp)
        x = w.merge(g[g.season == 2026][['week', 'home_team', 'away_team', 'home_score', 'away_score', 'spread_line', 'total_line']], on=['week', 'home_team', 'away_team'], how='inner')
        sc = x[(x.wb_home_score != x.home_score) | (x.wb_away_score != x.away_score)]
        ln = (-x.wb_close_home_line) - x.spread_line; tt = x.wb_close_total - x.total_line
        L += [f'- **2026 vs your workbook:** {len(x)} games matched; score mismatches: **{len(sc)}**.', '', '## Betting lines (2026, vs your workbook\'s 5-source consensus close)', '',
              f'- Spread: exact match {(ln == 0).mean()*100:.0f}%, within 0.5 pts {(ln.abs() <= 0.5).mean()*100:.0f}%, mean absolute difference {ln.abs().mean():.2f} pts, largest {ln.abs().max():.1f}.',
              f'- Total: exact match {(tt == 0).mean()*100:.0f}%, within 0.5 pts {(tt.abs() <= 0.5).mean()*100:.0f}%, mean absolute difference {tt.abs().mean():.2f} pts.',
              '- Differences are expected (different books, and the exact closing moment); none is large enough to suggest a wrong game or a flipped sign.']
        big = x[ln.abs() >= 1.5]
        if len(big): L.append('- Spread differences of 1.5+ pts: ' + ', '.join(f'wk{r.week} {r.away_team}@{r.home_team} (nflverse {r.spread_line:+g}, workbook {-r.wb_close_home_line:+g})' for r in big.itertuples()))
    # ---------- starting QBs
    L += ['', '## Starting QBs', '',
          '- **Fix applied:** games.csv sometimes lists the QB who played most rather than the one who started (e.g. Week 17 rest games). '
          f'The model now uses the QB on each team\'s first dropback (players listed at QB only): **{int(g.qb_fixed.sum())} team-games corrected**. '
          'Before the fix nflverse and nfelo disagreed on 76 games; the line below is after it.']
    m2 = m.copy()
    m2['ne_hq'] = np.where(m2.t1 == m2.home_team, m2.qb1, m2.qb2); m2['ne_aq'] = np.where(m2.t1 == m2.home_team, m2.qb2, m2.qb1)
    ok = m2.home_qb_name.notna() & m2.ne_hq.notna()
    mis = m2[ok & ((m2.home_qb_name.map(norm_name) != m2.ne_hq.map(norm_name)) | (m2.away_qb_name.map(norm_name) != m2.ne_aq.map(norm_name)))]
    L.append(f'- **nflverse vs nfelo starter:** {ok.sum():,} games compared; disagreements: **{len(mis)}** ({len(mis)/ok.sum()*100:.1f}%).')
    if len(mis):
        L.append('  Examples: ' + '; '.join(f'{r.game_id_x}: nflverse {r.away_qb_name} / {r.home_qb_name}, nfelo {r.ne_aq} / {r.ne_hq}' for r in mis.head(6).itertuples()))
    qb = pd.read_csv(os.path.join(CACHE, 'qb_games.csv')); qb['team'] = qb.team.replace(FRANCHISE).replace({'LAR': 'LA', 'WSH': 'WAS'})
    top = qb.sort_values('dropbacks', ascending=False).drop_duplicates(['game_id', 'team'])
    gg = played[['game_id', 'season', 'home_team', 'away_team', 'home_qb_id', 'away_qb_id']]
    t = pd.concat([gg.rename(columns={'home_team': 'team', 'home_qb_id': 'qb'})[['game_id', 'season', 'team', 'qb']],
                   gg.rename(columns={'away_team': 'team', 'away_qb_id': 'qb'})[['game_id', 'season', 'team', 'qb']]])
    t = t.merge(top[['game_id', 'team', 'player_id', 'dropbacks']], on=['game_id', 'team'], how='inner')
    tot = qb.groupby(['game_id', 'team']).dropbacks.sum().rename('team_db'); t = t.join(tot, on=['game_id', 'team'])
    st = qb.rename(columns={'player_id': 'qb', 'dropbacks': 'starter_db'})[['game_id', 'team', 'qb', 'starter_db']]
    t = t.merge(st, on=['game_id', 'team', 'qb'], how='left'); t['share'] = t.starter_db.fillna(0) / t.team_db
    diff = t[t.qb != t.player_id]
    L.append(f'- **Listed starter vs the QB with most dropbacks (play-by-play):** {len(t):,} team-games; different in **{len(diff)}** ({len(diff)/len(t)*100:.1f}%). '
             f'In {int((diff.share < 0.5).sum())} of these the listed starter had under half the dropbacks: these are mostly starters who left injured or were benched mid-game '
             '(used in round 4 as the "QB left the game" signal), not data errors.')
    # ---------- team stats vs official
    L += ['', '## Team stats (our play-by-play aggregates vs nflverse official team stats)', '', '| Season | Team-games | Interceptions thrown | Lost fumbles | Max abs difference |', '|---|---|---|---|---|']
    tg = pd.read_csv(os.path.join(CACHE, 'team_games.csv'))
    for s in (2018, 2025, 2026):
        o = pd.read_csv(os.path.join(AUD, f'stats_team_week_{s}.csv')); o = o[o.season_type == 'REG']
        o['fl'] = o.sack_fumbles_lost + o.rushing_fumbles_lost + o.receiving_fumbles_lost
        x = tg[tg.season == s].merge(o, left_on=['game_id', 'team'], right_on=['game_id', 'team'], how='inner')
        di = (x.ints - x.passing_interceptions).abs(); dfl = (x.fumbles_lost - x.fl).abs()
        L.append(f'| {s} | {len(x)} | {(di == 0).mean()*100:.1f}% exact | {(dfl == 0).mean()*100:.1f}% exact | INT {di.max():.0f}, fumbles {dfl.max():.0f} |')
    L.append('\nOur lost-fumble count also includes fumbles lost on special-teams returns, which the official offensive totals leave out; small differences there are expected.')
    # ---------- player stats vs official
    L += ['', '## Player stats (our play-by-play vs nflverse official player stats)', '', '| Season | Receiver-games | Targets exact | QB-games | Dropbacks ≥ attempts + sacks | Mean dropbacks − (att + sacks) |', '|---|---|---|---|---|---|']
    pw = pd.read_csv(os.path.join(CACHE, 'player_weeks.csv'))
    for s in (2012, 2018, 2024, 2026):
        o = pd.read_csv(os.path.join(AUD, f'stats_player_week_{s}.csv'), low_memory=False); o = o[o.season_type == 'REG']
        x = pw[(pw.season == s) & (pw.targets > 0)].merge(o[['game_id', 'player_id', 'targets']].rename(columns={'player_id': 'gsis_id', 'targets': 'off_t'}), on=['game_id', 'gsis_id'], how='inner')
        q = qb[qb.season == s].merge(o[['game_id', 'player_id', 'attempts', 'sacks_suffered']].rename(columns={'player_id': 'player_id'}), on=['game_id', 'player_id'], how='inner')
        q = q[q.attempts > 0]; d = q.dropbacks - (q.attempts + q.sacks_suffered)
        L.append(f'| {s} | {len(x):,} | {(x.targets == x.off_t).mean()*100:.1f}% | {len(q):,} | {(d >= 0).mean()*100:.1f}% | {d.mean():+.2f} (scrambles count as dropbacks) |')
    # ---------- QB EPA 2026 vs original workbook
    qbp = os.path.join(INPUTS, 'original_workbook_qbs_2026.csv')
    if os.path.exists(qbp):
        w = pd.read_csv(qbp); q = qb[(qb.season == 2026) & (qb.week <= 8)].groupby('player_id')[['dropbacks', 'qb_epa']].sum()
        names = pd.concat([g[['home_qb_id', 'home_qb_name']].set_axis(['i', 'n'], axis=1), g[['away_qb_id', 'away_qb_name']].set_axis(['i', 'n'], axis=1)]).dropna().drop_duplicates('i').set_index('i').n
        q['name'] = names.reindex(q.index).map(norm_name).values
        w['nm'] = w.name.map(norm_name); x = w.merge(q, left_on='nm', right_on='name', how='inner')
        x['epa_db'] = x.qb_epa / x.dropbacks
        L += ['', '## 2026 QB EPA per dropback vs your original workbook (through Week 8)', '',
              f'- {len(x)} QBs matched. Dropbacks: mean difference {(x.dropbacks - x.wb_dropbacks).mean():+.1f}; EPA/dropback: mean absolute difference {(x.epa_db - x.wb_epa_db).abs().mean():.3f}, '
              f'correlation {np.corrcoef(x.epa_db, x.wb_epa_db)[0, 1]:.3f}. (The workbook\'s numbers were taken from the same play-by-play on an earlier date, so small differences are expected.)']
    open(os.path.join(RESULTS, 'audit_data.md'), 'w').write('\n'.join(L) + '\n'); print('\n'.join(L))


if __name__ == '__main__':
    main()
