"""Check the Python tipping engine against the numbers your original workbook shows (its cached values), cell by cell.
The engine is run WITHOUT the two new tippers (Model, Vegas line) so every stat is defined exactly as in the original.
Usage: python3 research/verify_tipping.py <original NFL_Tipping_final_56.xlsx>   -> results/tipping_engine_check.md
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import warnings; warnings.filterwarnings('ignore')
import numpy as np, pandas as pd
from openpyxl import load_workbook
from nflmodel.common import ROOT, RESULTS
from nflmodel.tipping_inputs import read_inputs
from nflmodel import tipping as T, tipping_stats as TS, tipping_sheets as SH

INP = os.path.join(ROOT, 'inputs', 'tipping_inputs.xlsx')
CHECKS, BAD = [0], []


def eq(a, b, tol=1e-6):
    if (a is None or a == '') and (b is None or (isinstance(b, float) and np.isnan(b)) or b == ''): return True
    if isinstance(a, (int, float)) and isinstance(b, (int, float, np.integer, np.floating)):
        return (np.isnan(a) and np.isnan(b)) or abs(float(a) - float(b)) <= tol * max(1, abs(float(a)))
    return str(a).strip() == str(b).strip()


def cmp(sheet, cell, want, got):
    CHECKS[0] += 1
    if not eq(want, got): BAD.append(f'{sheet}!{cell}: workbook {want!r} vs engine {got!r}')


def main():
    wbv = load_workbook(sys.argv[1], data_only=True)
    inp = read_inputs(INP)
    ctx = SH.compute(inp, include_new=False)
    for sheet, cells in SH.original_cells(ctx).items():
        ws = wbv[sheet]
        for cell, got in cells.items():
            cmp(sheet, cell, ws[cell].value, got)
    L = ['# Tipping engine check (generated by research/verify_tipping.py)', '',
         'Every number below is recomputed in Python from inputs/tipping_inputs.xlsx and compared with the value your original workbook shows.', '',
         f'- Cells compared: **{CHECKS[0]:,}**', f'- Mismatches: **{len(BAD)}**']
    if BAD: L += ['', '## Mismatches', ''] + [f'- {b}' for b in BAD[:300]]
    open(os.path.join(RESULTS, 'tipping_engine_check.md'), 'w').write('\n'.join(L) + '\n'); print('\n'.join(L[:8 + min(len(BAD), 60)]))


if __name__ == '__main__':
    main()
