"""Final before-vs-after evaluation. Writes results/report.md and results/predictions_new.csv.

Compares, walk-forward, on development (2012-19), holdout (2020-25) and live 2026 (weeks played so far):
  original model (baseline.py), new model (selected factors), Vegas closing line,
  and "new model + line" (blend weight fit only on earlier seasons) to test whether the model adds anything to the market.
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))   # nfl-model/ on the path
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from nflmodel.common import RESULTS, INPUTS, config
import json, os, warnings
import numpy as np, pandas as pd
from scipy.stats import norm
warnings.filterwarnings('ignore')
from nflmodel.features import build_features, walk_forward, load_all
from nflmodel.extra import build_extra, adjusted_line
from nflmodel.metrics import evaluate, line_as_model, calibration_table, no_vig_prob
import baseline

SEL = config(); PARAMS = SEL['ratings']
PERIODS = {'Development 2012-19': range(2012, 2020), 'Holdout 2020-25': range(2020, 2026), 'Live 2026 (wks 1-8)': range(2026, 2027)}


def blend_with_line(d):
    """pred = line + a*(model - line); a fit on earlier seasons' out-of-sample predictions only."""
    out = []
    for S in sorted(d.season.unique()):
        tr = d[(d.season < S) & d.result.notna() & d.spread_line.notna()]; te = d[d.season == S].copy()
        if len(tr) < 500: continue
        x = (tr.pred - tr.spread_line).values; y = (tr.result - tr.spread_line).values
        a = float(np.clip((x @ y) / (x @ x), 0, 1))
        te['pred'] = te.spread_line + a * (te.pred - te.spread_line); te['blend_a'] = a
        sig = np.sqrt(np.mean((tr.spread_line + a * x - tr.result) ** 2))
        te['prob'] = norm.cdf(te.pred / sig)
        out.append(te)
    return pd.concat(out)


def table(models, seasons, weeks=None):
    lines = ['| Model | Games | Tips right | RMSE (pts) | MAE | ATS vs close | ATS when edge >=3 | Brier | Log-loss |', '|---|---|---|---|---|---|---|---|---|']
    for name, d in models.items():
        x = d[d.season.isin(seasons)]
        if weeks is not None: x = x[x.week.isin(weeks)]
        if x.empty: continue
        e = evaluate(x)
        ats = '—' if name.startswith('Vegas') else f"{e['ATS_W']}-{e['ATS_L']} ({e['ATS_pct']*100:.1f}%)"
        a3 = '—' if name.startswith('Vegas') else e['ATS_3+']
        lines.append(f"| {name} | {e['games']} | {e['SU_acc']*100:.1f}% | {e['RMSE']:.2f} | {e['MAE']:.2f} | {ats} | {a3} | {e['Brier']:.4f} | {e['LogLoss']:.4f} |")
    return '\n'.join(lines)


def main():
    data = load_all()
    f = build_extra(build_features(PARAMS, data=data), data[0], data[1])
    new = walk_forward(f, SEL['features'], range(2010, 2027), **SEL['opts'])
    R1 = dict(features=SEL['round1_features'], opts={})
    r1 = walk_forward(f, R1['features'], range(2010, 2027), **R1['opts'])
    adj = pd.concat([adjusted_line(f, s, SEL['line_adjust'])[0] for s in range(2012, 2027)])
    adj = adj[adj.spread_line.notna()].assign(pred=lambda d: d.pred_adj, prob=lambda d: d.prob_adj)
    keep = ['game_id', 'season', 'week', 'game_type', 'home_team', 'away_team', 'result', 'spread_line', 'pred', 'prob', 'sigma']
    new[keep].round(4).to_csv(os.path.join(RESULTS, 'predictions_new.csv'), index=False)   # slim: what later research needs
    base = baseline.predict(range(2010, 2027))
    base_pr = base.assign(pred=base.pr_pred, prob=base.pr_prob)
    line = line_as_model(new)
    blend = blend_with_line(r1)
    M = {'Original tips engine': base, 'Original PR score (+1.5 HFA)': base_pr, 'Round-1 model': r1, 'New model': new,
         'Round-1 model blended with line': blend, 'Adjusted line (line + special teams + market drift)': adj, 'Vegas closing line': line}
    R = ['# Backtest report (generated by report.py)\n',
         f"New model features: `{', '.join(SEL['features'])}`  options: `{SEL['opts']}`\n",
         'All numbers are walk-forward: every prediction uses only games before that week; blend weights are fit only on earlier seasons.\n',
         'Original PR score has no Week 1 prediction, so its rows cover Weeks 2-18 only.\n']
    for p, s in PERIODS.items():
        R += [f'\n## {p}\n', table(M, list(s))]
    R += ['\n## 2026 Weeks 3-8 (the window used in the original README)\n', table(M, [2026], range(3, 9))]
    orig = os.path.join(INPUTS, 'original_workbook_picks_2026.json')
    if os.path.exists(orig):
        mp = pd.DataFrame(json.load(open(orig)))
        mp[['a', 'h']] = mp.g.str.split('@', expand=True); mp[['a', 'h']] = mp[['a', 'h']].replace({'LAR': 'LA', 'WSH': 'WAS'})
        w = mp.merge(new[new.season == 2026][['game_id', 'week', 'home_team', 'away_team', 'result', 'spread_line', 'home_moneyline', 'away_moneyline']],
                     left_on=['w', 'h', 'a'], right_on=['week', 'home_team', 'away_team'])
        w['season'] = 2026; w['pred'] = w.pred.astype(float); w['prob'] = norm.cdf(w.pred / 13.0)
        R += ['\nOriginal workbook\'s own 2026 predictions (with DVOA, hand injuries, eye test), same games:\n',
              table({'Original workbook (actual picks)': w}, [2026], range(3, 9))]
        ids = set(w[w.week.between(3, 8)].game_id) if 'game_id' in w else set()
        keep = lambda d: d[d.game_id.isin(ids)]
        R += ['\nEvery model on exactly those same games:\n',
              table({'Original workbook (actual picks)': w, **{k: keep(v) for k, v in M.items()}}, [2026], range(3, 9))]
    # by season
    R += ['\n## Season by season (tips right % / RMSE)\n', '| Season | Original | New | Adjusted line | Line | New ATS |', '|---|---|---|---|---|---|']
    for s in range(2012, 2027):
        cells = []
        for nm in ('Original tips engine', 'New model', 'Adjusted line (line + special teams + market drift)', 'Vegas closing line'):
            e = evaluate(M[nm][M[nm].season == s]); cells.append(f"{e['SU_acc']*100:.1f}% / {e['RMSE']:.2f}")
        e = evaluate(new[new.season == s])
        R.append(f"| {s} | " + ' | '.join(cells) + f" | {e['ATS_W']}-{e['ATS_L']} |")
    # early vs late season
    R += ['\n## By part of season (holdout 2020-25)\n']
    for lab, wk in (('Weeks 1-4', range(1, 5)), ('Weeks 5-9', range(5, 10)), ('Weeks 10-18', range(10, 19))):
        R += [f'\n**{lab}**\n', table({k: M[k] for k in ('Original tips engine', 'New model', 'Vegas closing line')}, list(range(2020, 2026)), wk)]
    # consistency
    R += ['\n## Week-to-week consistency (holdout 2020-25)\n', '| Model | SD of weekly tip % | Worst 10% of weeks | Weeks with >= 50% tips | SD of weekly RMSE |', '|---|---|---|---|---|']
    for nm in ('Original tips engine', 'New model', 'Adjusted line (line + special teams + market drift)', 'Vegas closing line'):
        x = M[nm][M[nm].season.between(2020, 2025) & M[nm].result.notna()]
        e = evaluate(x)
        wk = x[x.result != 0].groupby(['season', 'week']).apply(lambda z: (np.sign(z.pred) == np.sign(z.result)).mean())
        R.append(f"| {nm} | {e['wk_acc_sd']*100:.1f} pts | {e['wk_acc_p10']*100:.1f}% | {(wk >= 0.5).mean()*100:.0f}% | {e['wk_RMSE_sd']:.2f} |")
    # head-to-head weekly vs line
    x = new[new.season.between(2020, 2025) & new.result.notna() & (new.result != 0)].copy()
    x['m'] = np.sign(x.pred) == np.sign(x.result); x['l'] = np.sign(x.spread_line) == np.sign(x.result)
    wk = x.groupby(['season', 'week'])[['m', 'l']].sum()
    R.append(f"\nNew model vs line, weekly tips (holdout): model ahead {int((wk.m > wk.l).sum())} weeks, level {int((wk.m == wk.l).sum())}, behind {int((wk.m < wk.l).sum())}.\n")
    # calibration
    R += ['\n## Win-probability calibration (holdout 2020-25)\n', '| Predicted range | Games | New model predicted | Actual home win % | Line (no-vig) predicted | Actual |', '|---|---|---|---|---|---|']
    a = calibration_table(new[new.season.between(2020, 2025)]); b = calibration_table(line[line.season.between(2020, 2025)])
    for (i, r), (j, q) in zip(a.iterrows(), b.iterrows()):
        R.append(f"| {i} | {r.games} | {r.predicted*100:.1f}% | {r.actual*100:.1f}% | {q.predicted*100:.1f}% (n={q.games}) | {q.actual*100:.1f}% |")
    # betas
    last = new[new.season == 2026]
    if not last.empty:
        R += ['\n## Blend weights used for 2026 (fit on 2009-2025)\n', '| Feature | Weight |', '|---|---|']
        for k in SEL['features']:
            R.append(f"| {k} | {last['b_' + k].iloc[0]:.3f} |")
        R.append(f"\nResult spread (sigma) used for win probabilities: {last.sigma.iloc[0]:.2f} pts")
        _, sg, cf = adjusted_line(f, 2026, SEL['line_adjust'])
        R.append(f"\nAdjusted line for 2026 = closing line + " + ' + '.join(f'{v:.3f} x {k}' for k, v in cf.items()) + f" (result spread {sg:.2f} pts)")
    open(os.path.join(RESULTS, 'report.md'), 'w').write('\n'.join(R) + '\n')
    print('\n'.join(R))


if __name__ == '__main__':
    main()
