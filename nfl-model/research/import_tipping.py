"""One-time import of the original NFL_Tipping workbook into inputs/tipping_inputs.xlsx, with a cell-by-cell check.

Usage: python3 research/import_tipping.py <original NFL_Tipping_final_56.xlsx> [--force]
Refuses to overwrite an existing inputs file unless --force is given (your entries are never overwritten by accident).
Every typed (non-formula) cell in the original's week tabs, odds feeds, expert picks, locks and settings is compared with the
new inputs file; the result goes to results/tipping_import_check.md.
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import warnings; warnings.filterwarnings('ignore')
from openpyxl import load_workbook
from nflmodel.common import ROOT, RESULTS
from nflmodel.tipping_inputs import import_original, G0, O0, E0, LOCK_ROW, NG, NW

DST = os.path.join(ROOT, 'inputs', 'tipping_inputs.xlsx')


def typed(c):
    return c.value is not None and not (isinstance(c.value, str) and c.value.startswith('='))


def check(src, dst):
    o, n = load_workbook(src), load_workbook(dst)
    checks, bad = 0, []
    def cmp(label, a, b):
        nonlocal checks
        checks += 1
        if a != b: bad.append(f'{label}: original {a!r} vs inputs {b!r}')
    for wk in range(1, NW + 1):
        ow, nw = o[f'Wk {wk}'], n[f'Wk {wk}']
        for i in range(NG):
            for oc, nc, lab in ((2, 2, 'kickoff'), (21, 3, 'slot'), (3, 4, 'away'), (4, 5, 'home'), (11, 6, 'away pts'), (12, 7, 'home pts'), (5, 8, 'your tip'), (22, 11, 'notes')):
                c = ow.cell(10 + i, oc)
                if typed(c): cmp(f'Wk {wk} game {i + 1} {lab}', c.value, nw.cell(G0 + i, nc).value)
            for oc, nc, lab in ((7, 9, 'spread bet'), (15, 10, 'over/under bet')):
                c = ow.cell(30 + i, oc)
                if typed(c): cmp(f'Wk {wk} game {i + 1} {lab}', c.value, nw.cell(G0 + i, nc).value)
            for j in range(16):
                c = ow.cell(95 + i, 3 + j)
                if typed(c): cmp(f'Wk {wk} game {i + 1} odds col {j + 1}', c.value, nw.cell(O0 + i, 3 + j).value)
            for e in range(30):
                c = ow.cell(52 + e, 3 + i)
                if typed(c): cmp(f'Wk {wk} game {i + 1} expert row {e + 1}', c.value, nw.cell(E0 + e, 3 + i).value)
            c = ow.cell(86, 3 + i)
            if typed(c): cmp(f'Wk {wk} game {i + 1} stats-model row', c.value, nw.cell(E0 + 30, 3 + i).value)
        for oc, nc, lab in ((3, 2, 'tip lock'), (8, 5, 'spread lock'), (13, 8, 'O/U lock')):
            c = o['Money'].cell(55 + wk, oc)
            if typed(c): cmp(f'Wk {wk} {lab}', c.value, nw.cell(LOCK_ROW, nc).value)
    for r in range(14, 45):
        cmp(f'Tipper {r - 13} name', o['Setup'].cell(r, 7).value, n['Tippers'].cell(r - 9, 2).value)
        cmp(f'Tipper {r - 13} outlet', o['Setup'].cell(r, 8).value, n['Tippers'].cell(r - 9, 3).value)
    for oc, nc, lab in (('C13', 'B5', 'tip stake'), ('C16', 'B6', 'spread stake'), ('C15', 'B7', 'O/U stake'), ('C14', 'B9', 'rank by')):
        cmp(f'Setting {lab}', o['Setup'][oc].value, n['Settings'][nc].value)
    cmp('Head to Head opponent', o['Head to Head']['D4'].value, n['Settings']['B10'].value)
    # anything typed in the original that the import does not carry (should be nothing)
    extra = []
    for wk in range(1, NW + 1):
        ow = o[f'Wk {wk}']
        for r, cols in ((range(10, 26), {1, 2, 3, 4, 5, 11, 12, 21, 22}), (range(30, 46), {1, 7, 15}), (range(52, 82), set(range(1, 19)) | {21}),
                        (range(82, 87), {1, 21} | set(range(3, 19))), (range(95, 111), {1} | set(range(3, 19)))):
            for rr in r:
                for c in ow[rr]:
                    if typed(c) and c.column not in cols and not (82 <= rr <= 85): extra.append(f'Wk {wk} {c.coordinate}={c.value!r}')
    return checks, bad, extra


def main():
    src = sys.argv[1]
    if os.path.exists(DST) and '--force' not in sys.argv:
        print(f'{DST} already exists: not overwriting (use --force only if you really mean to replace your entries).')
    else:
        import_original(src, DST); print('wrote', DST)
    checks, bad, extra = check(src, DST)
    L = ['# Tipping import check (generated by research/import_tipping.py)', '',
         f'Original: `{os.path.basename(src)}`  →  `inputs/tipping_inputs.xlsx`', '',
         f'- Typed cells compared: **{checks:,}**', f'- Mismatches: **{len(bad)}**', f'- Typed cells in the original that are not carried over: **{len(extra)}**']
    if bad: L += ['', '## Mismatches', ''] + [f'- {b}' for b in bad]
    if extra: L += ['', '## Not carried over', ''] + [f'- {x}' for x in extra[:100]]
    open(os.path.join(RESULTS, 'tipping_import_check.md'), 'w').write('\n'.join(L) + '\n'); print('\n'.join(L))


if __name__ == '__main__':
    main()
